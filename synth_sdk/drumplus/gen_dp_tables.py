#!/usr/bin/env python3
"""Generate drumplus/dp_tables.h: filter cutoff table for the drum+ voice filter (ZDF state-variable filter).
g[i] = tan(pi * fc / 44100) in Q16 for fc = 30 Hz * (16000 / 30)^(i / 127), i = 0..127."""
import math, os
HERE = os.path.dirname(os.path.abspath(__file__))
g = [round(math.tan(math.pi * 30 * (16000 / 30) ** (i / 127) / 44100) * 65536) for i in range(128)]
out = ['/* generated by drumplus/gen_dp_tables.py - do not edit */', '#include <stdint.h>',
       '/* tan(pi fc / 44100) in Q16, fc = 30 Hz .. 16 kHz exponential (128 steps) */',
       'static const uint32_t dp_filter_g[128] __attribute__((unused)) = {']
for i in range(0, 128, 8):
    out.append('    ' + ', '.join(str(v) for v in g[i:i + 8]) + ',')
out.append('};')
hz = [round(30 * (16000 / 30) ** (i / 127)) for i in range(128)]
out.append('/* the same cutoff steps in Hz (screen labels) */')
out.append('static const uint16_t dp_cutoff_hz[128] __attribute__((unused)) = {')
for i in range(0, 128, 8):
    out.append('    ' + ', '.join(str(v) for v in hz[i:i + 8]) + ',')
out.append('};')
open(os.path.join(HERE, 'dp_tables.h'), 'w').write('\n'.join(out) + '\n')
print('ok', g[0], g[64], g[127])
