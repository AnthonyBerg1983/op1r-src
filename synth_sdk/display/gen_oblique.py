#!/usr/bin/env python3
"""Oblique Strategies cards -> build/oblique_data.c (docs/23): lowercase text (the OP-1 font draws a-z as capitals),
pre-wrapped lines per card. Widths for wrapping come from the stock opfont.svg (build time only; no font data is
emitted). The firmware Text object centres each line and gives the exact x of every character at runtime.

usage: gen_oblique.py <opfont.svg> <cards.txt> <out.c>"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import svgfont

CELL = 56.7                 # glyph cell height in font units
TEXT_H = 9.0                # cap height in px at Text size OB_SIZE (estimate; checked on hardware)
GAP, SPACE = 3.0, 6.0       # px between glyphs, advance of ' ' (estimate)
MAX_W = 276.0               # wrap width (screen 320, frame + margin)
MAX_LINES = 6
EXTRA_W = {"'": 3.0, '(': 5.0, ')': 5.0, '[': 5.0, ']': 5.0}   # drawn by us; the firmware places a space there
EXTRA = set(EXTRA_W)


def widths(svg):
    g = svgfont.load(svg)
    w = {}
    for ch, polys in g.items():
        pts = [p for poly in polys for p in poly]
        if pts and not ch.isupper():
            w[ch] = (max(p[0] for p in pts) - min(p[0] for p in pts)) * TEXT_H / CELL
    return w


def text_w(w, s):
    out = 0.0
    for i, c in enumerate(s):
        out += SPACE if c == ' ' or c in EXTRA else w.get(c, SPACE)
        if i + 1 < len(s): out += GAP
    return out


def wrap(w, text):
    lines, cur = [], ''
    for word in text.split():
        t = (cur + ' ' + word) if cur else word
        if cur and text_w(w, t) > MAX_W:
            lines.append(cur); cur = word
        else:
            cur = t
    if cur: lines.append(cur)
    return lines


def load_cards(path):
    return [l.strip().lower() for l in open(path, encoding='utf-8') if l.strip() and not l.startswith('#')]


def build(svg, cards_path):
    w = widths(svg)
    cards = load_cards(cards_path)
    out = []
    for c in cards:
        bad = set(c) - set(w) - EXTRA - {' '}
        assert not bad, f'unsupported characters {bad!r} in {c!r}'
        ls = wrap(w, c)
        assert len(ls) <= MAX_LINES, f'card too long ({len(ls)} lines): {c!r}'
        out.append(ls)
    return out, w


def emit(cards, path):
    def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
    lines, first = [], [0]
    for ls in cards:
        lines += ls; first.append(len(lines))
    with open(path, 'w') as f:
        f.write('/* generated by display/gen_oblique.py from screens/oblique/cards.txt: do not edit */\n')
        f.write('#include <stdint.h>\n')
        f.write(f'const int ob_ncards = {len(cards)};\n')
        f.write('const uint16_t ob_first[] = {' + ','.join(map(str, first)) + '};\n')
        f.write('const char *const ob_lines[] = {\n' + ',\n'.join('    ' + q(l) for l in lines) + '\n};\n')


if __name__ == '__main__':
    cards, _ = build(sys.argv[1], sys.argv[2])
    emit(cards, sys.argv[3])
    print(f'{len(cards)} cards, max {max(map(len, cards))} lines -> {sys.argv[3]}')
