#!/usr/bin/env python3
"""Generate display/quadlfo.svg + lfo/quadlfo_geom.h (screen of the quad LFO).

Four LFO rows: an encoder-coloured dot and a short lane line with a centre mark. Code draws the amount span, the
moving output tick, frequency, amount, target glyph + target dot and the type (lfo/quadlfo.c).
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
GREY, LILAC = '#6F7173', '#AEB1DC'
COLS = ['#4D9EFF', '#00ED95', '#FFFFFF', '#FF3A5D']
LANE_Y = [18, 54, 90, 126]                     # rows; content stays above ~y 140
DOT_X, LANE_X0, LANE_X1 = 10, 22, 94
FREQ_X, AMT_X, GLYPH_X, TDOT_X, TYPE_X = 102, 166, 220, 240, 252   # text top-left x (Q0)
TICK_H = 9                                     # output tick half height
SPAN_W = 0x1000                                # amount span line width (Q10)

def svg():
    o = ['<?xml version="1.0" encoding="utf-8"?>',
         '<svg version="1.1" id="Layer_1" xmlns="http://www.w3.org/2000/svg" x="0px" y="0px"',
         '\t width="320px" height="160px" viewBox="0 0 320 160">',
         '<!-- generated by display/gen_quadlfo_svg.py - quad LFO: rows; values and glyphs drawn by code -->']
    mid = (LANE_X0 + LANE_X1) // 2
    for i, y in enumerate(LANE_Y):
        o.append(f'<circle fill="{COLS[i]}" cx="{DOT_X}" cy="{y}" r="4"/>')
        o.append(f'<line fill="none" stroke="{GREY}" stroke-width="1" x1="{LANE_X0}" y1="{y}" x2="{LANE_X1}" y2="{y}"/>')
        o.append(f'<line fill="none" stroke="{GREY}" stroke-width="1" x1="{mid}" y1="{y - 4}" x2="{mid}" y2="{y + 4}"/>')
    o.append('</svg>')
    return '\n'.join(o) + '\n'

def header():
    rgb = lambda c: '{ %d, %d, %d, 255 }' % tuple(int(c[i:i + 2], 16) for i in (1, 3, 5))
    mid = (LANE_X0 + LANE_X1) // 2
    d = dict(DOT_X=DOT_X, LANE_X0=LANE_X0, LANE_X1=LANE_X1, LANE_MID=mid, LANE_HALF=(LANE_X1 - LANE_X0) // 2,
             FREQ_X=FREQ_X, AMT_X=AMT_X, GLYPH_X=GLYPH_X, TDOT_X=TDOT_X, TYPE_X=TYPE_X, TICK_H=TICK_H)
    return '\n'.join(['/* generated by display/gen_quadlfo_svg.py - geometry of display/quadlfo.svg */'] +
        [f'#define QL_{k} {v}' for k, v in d.items()] + [f'#define QL_SPAN_W {SPAN_W:#x}',
        'static const int16_t ql_lane_y[4] = { ' + ', '.join(map(str, LANE_Y)) + ' };',
        'static const uint8_t ql_col[4][4] = { ' + ', '.join(rgb(c) for c in COLS) + ' };',
        'static const uint8_t ql_dim[4] = ' + rgb(GREY) + ';',
        'static const uint8_t ql_lilac[4] = ' + rgb(LILAC) + ';',
        'static const uint8_t ql_white[4] = { 255, 255, 255, 255 };']) + '\n'

if __name__ == '__main__':
    open(os.path.join(HERE, 'quadlfo.svg'), 'w').write(svg())
    open(os.path.join(os.path.dirname(HERE), 'lfo', 'quadlfo_geom.h'), 'w').write(header())
    print('ok')
