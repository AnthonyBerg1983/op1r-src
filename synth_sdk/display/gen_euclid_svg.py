#!/usr/bin/env python3
"""Generate display/euclid.svg + seq/euclid_geom.h (screen of the euclid sequencer, seq/euclid.c).

Static: the big ring (thin grey circle) and six faint mini-ring outlines (one per sequencer slot).
Code draws the step dots, playhead, note name, the four encoder rows and the mini-ring pulses.
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
GREY, DIM = '#6F7173', '#4A4C4E'
COLS = ['#4D9EFF', '#00ED95', '#FFFFFF', '#FF3A5D']
GREEN = '#00ED95'
MINI_X0, MINI_DX, MINI_Y, MINI_R = 24, 32, 20, 9
RING_X, RING_Y, RING_R = 96, 90, 38
TEXT_X, NOTE_Y, ROW_Y0, ROW_DY = 232, 11, 50, 26   # note in line with the mini rings
PAT_X, PAT_Y = 8, 124                             # pattern number 'P1'..'P4', bottom left (text top)
LVL_X, LVL_Y0, LVL_Y1 = 311, 14, 138               # level bar (style of tape.svg mixervol); visible area ends ~y 140

def svg():
    o = ['<?xml version="1.0" encoding="utf-8"?>',
         '<svg version="1.1" id="Layer_1" xmlns="http://www.w3.org/2000/svg" x="0px" y="0px"',
         '\t width="320px" height="160px" viewBox="0 0 320 160">',
         '<!-- generated by display/gen_euclid_svg.py - euclid sequencer: rings; dots and text drawn by code -->']
    for k in range(6):
        o.append(f'<circle fill="none" stroke="{DIM}" stroke-width="1" cx="{MINI_X0 + k * MINI_DX}" cy="{MINI_Y}" r="{MINI_R}"/>')
    o.append(f'<circle fill="none" stroke="{GREY}" stroke-width="1" cx="{RING_X}" cy="{RING_Y}" r="{RING_R}"/>')
    o.append('</svg>')
    return '\n'.join(o) + '\n'

def header():
    rgb = lambda c, f=1.0: '{ %d, %d, %d, 255 }' % tuple(int(int(c[i:i + 2], 16) * f) for i in (1, 3, 5))
    return '\n'.join(['/* generated by display/gen_euclid_svg.py - geometry of display/euclid.svg */',
        f'#define EU_MINI_X0 {MINI_X0}', f'#define EU_MINI_DX {MINI_DX}', f'#define EU_MINI_Y {MINI_Y}', f'#define EU_MINI_R {MINI_R}',
        f'#define EU_RING_X {RING_X}', f'#define EU_RING_Y {RING_Y}', f'#define EU_RING_R {RING_R}',
        f'#define EU_TEXT_X {TEXT_X}', f'#define EU_NOTE_Y {NOTE_Y}', f'#define EU_ROW_Y0 {ROW_Y0}', f'#define EU_ROW_DY {ROW_DY}',
        f'#define EU_PAT_X {PAT_X}', f'#define EU_PAT_Y {PAT_Y}',
        f'#define EU_LVL_X {LVL_X}', f'#define EU_LVL_Y0 {LVL_Y0}', f'#define EU_LVL_Y1 {LVL_Y1}',
        'static const uint8_t eu_col[4][4] = { ' + ', '.join(rgb(c) for c in COLS) + ' };',
        'static const uint8_t eu_green[4] = ' + rgb(GREEN) + ';',
        'static const uint8_t eu_dimgreen[4] = ' + rgb(GREEN, 0.35) + ';',
        'static const uint8_t eu_grey[4] = ' + rgb(GREY) + ';',
        'static const uint8_t eu_dimred[4] = ' + rgb(COLS[3], 0.35) + ';',
        'static const uint8_t eu_white[4] = { 255, 255, 255, 255 };']) + '\n'

if __name__ == '__main__':
    open(os.path.join(HERE, 'euclid.svg'), 'w').write(svg())
    open(os.path.join(os.path.dirname(HERE), 'seq', 'euclid_geom.h'), 'w').write(header())
    print('ok')
