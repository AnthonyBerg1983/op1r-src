#!/usr/bin/env python3
"""Generate display/dots.svg + seq/dots_geom.h (screen of the dots step sequencer, seq/dots.c).

Static: empty (the screen needs an SVG). Code draws the dots, cursor, playhead, slot
row, texts and the level bar.
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
GREY, DIM, LILAC = '#6F7173', '#4A4C4E', '#AEB1DC'
COLS = ['#4D9EFF', '#00ED95', '#FFFFFF', '#FF3A5D']
GREEN = '#00ED95'
SLOT_X0, SLOT_DX, SLOT_Y = 12, 24, 6              # slot numbers 1..6 (text top)
GRID_X0, GRID_DX, GRID_GAP = 22, 16, 5             # step i: x = X0 + i % 16 * DX + (i % 16 / 4) * GAP
GRID_Y0, GRID_DY = 38, 20                          # 4 rows of 16
INFO_Y = 118                                       # bottom text row (text top); visible area ends ~y 140
PAT_X, NOTE_X, PAR_X, REC_X = 8, 40, 136, 270   # REC: in the slot row

def gx(i): return GRID_X0 + i % 16 * GRID_DX + (i % 16 // 4) * GRID_GAP

def svg():
    o = ['<?xml version="1.0" encoding="utf-8"?>',
         '<svg version="1.1" id="Layer_1" xmlns="http://www.w3.org/2000/svg" x="0px" y="0px"',
         '\t width="320px" height="160px" viewBox="0 0 320 160">',
         '<!-- generated by display/gen_dots_svg.py - dots sequencer: dots and text drawn by code -->',
         '</svg>']
    return '\n'.join(o) + '\n'

def header():
    rgb = lambda c, f=1.0: '{ %d, %d, %d, 255 }' % tuple(int(int(c[i:i + 2], 16) * f) for i in (1, 3, 5))
    d = dict(SLOT_X0=SLOT_X0, SLOT_DX=SLOT_DX, SLOT_Y=SLOT_Y, GRID_X0=GRID_X0, GRID_DX=GRID_DX, GRID_GAP=GRID_GAP,
             GRID_Y0=GRID_Y0, GRID_DY=GRID_DY, INFO_Y=INFO_Y, PAT_X=PAT_X, NOTE_X=NOTE_X, PAR_X=PAR_X, REC_X=REC_X)
    return '\n'.join(['/* generated by display/gen_dots_svg.py - geometry of display/dots.svg */'] +
        [f'#define DT_{k} {v}' for k, v in d.items()] + [
        'static const uint8_t dt_col[4][4] = { ' + ', '.join(rgb(c) for c in COLS) + ' };',
        'static const uint8_t dt_green[4] = ' + rgb(GREEN) + ';',
        'static const uint8_t dt_dimgreen[4] = ' + rgb(GREEN, 0.35) + ';',
        'static const uint8_t dt_grey[4] = ' + rgb(GREY) + ';',
        'static const uint8_t dt_dim[4] = ' + rgb(DIM) + ';',
        'static const uint8_t dt_lilac[4] = ' + rgb(LILAC) + ';',
        'static const uint8_t dt_white[4] = { 255, 255, 255, 255 };']) + '\n'

if __name__ == '__main__':
    open(os.path.join(HERE, 'dots.svg'), 'w').write(svg())
    open(os.path.join(HERE, '..', 'seq', 'dots_geom.h'), 'w').write(header())
    print('-> display/dots.svg, seq/dots_geom.h')
