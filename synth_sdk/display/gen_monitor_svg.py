#!/usr/bin/env python3
"""Generate display/sysmon.svg: static frame of the resource monitor page (clock screen + T1, docs/18).

The SVG holds only what never changes: bar outlines, scale ticks, the MIDI in/out split. Bars, peak markers,
labels and numbers are drawn by the screen code each frame (Raster::line, firmware Text objects). Geometry is
shared with the C code through the ROWS table below (also written to screens/sysmon_geom.h).
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
SDK = os.path.dirname(HERE)

GREY, DIM = '#6F7173', '#3A3B3D'
BX0, BX1, BH = 56, 236, 10                       # bar x range and height
# (id, label, y top, colour, split) - split: two half bars (MIDI in / out)
ROWS = [('cpu', 'cpu', 14, '#4D9EFF', False),
        ('dsp', 'audio', 38, '#00ED95', False),
        ('ram', 'ram', 62, '#FFFFFF', False),
        ('disk', 'disk', 86, '#DFD9FF', False),
        ('midi', 'midi', 110, '#FF3A5D', True)]
MID = (BX0 + BX1) // 2                           # MIDI split: in = BX0..MID-4, out = MID+4..BX1


def bar_rects(split):
    return [(BX0, MID - 4), (MID + 4, BX1)] if split else [(BX0, BX1)]


def svg():
    o = ['<?xml version="1.0" encoding="utf-8"?>',
         '<svg version="1.1" id="Layer_1" xmlns="http://www.w3.org/2000/svg" x="0px" y="0px" width="320px" '
         'height="160px" viewBox="0 0 320 160">', '<g id="frame">']
    for rid, _, y, _, split in ROWS:
        for x0, x1 in bar_rects(split):
            o.append('<rect x="%d" y="%d" fill="none" stroke="%s" stroke-width="1" width="%d" height="%d"/>'
                     % (x0, y, GREY, x1 - x0, BH))
            for k in (1, 2, 3):                  # quarter ticks under the bar
                x = x0 + (x1 - x0) * k // 4
                o.append('<line fill="none" stroke="%s" stroke-width="1" x1="%d" y1="%d" x2="%d" y2="%d"/>'
                         % (DIM, x, y + BH + 1, x, y + BH + 4))
    o += ['</g>', '</svg>', '']
    return '\n'.join(o)


def header():
    h = ['/* generated by display/gen_monitor_svg.py */', '#pragma once',
         '#define SM_BX0 %d' % BX0, '#define SM_BX1 %d' % BX1, '#define SM_BH %d' % BH, '#define SM_MID %d' % MID,
         'enum { %s, SM_ROWS };' % ', '.join('SM_' + r[0].upper() for r in ROWS),
         'static const short sm_row_y[SM_ROWS] = { %s };' % ', '.join(str(r[2]) for r in ROWS),
         'static const char *const sm_row_label[SM_ROWS] = { %s };' % ', '.join('"%s"' % r[1] for r in ROWS),
         'static const unsigned char sm_row_rgb[SM_ROWS][3] = { %s };' % ', '.join(
             '{0x%s, 0x%s, 0x%s}' % (r[3][1:3], r[3][3:5], r[3][5:7]) for r in ROWS), '']
    return '\n'.join(h)


if __name__ == '__main__':
    open(os.path.join(HERE, 'sysmon.svg'), 'w').write(svg())
    os.makedirs(os.path.join(SDK, 'screens'), exist_ok=True)
    open(os.path.join(SDK, 'screens', 'sysmon_geom.h'), 'w').write(header())
    print('-> display/sysmon.svg, screens/sysmon_geom.h')
