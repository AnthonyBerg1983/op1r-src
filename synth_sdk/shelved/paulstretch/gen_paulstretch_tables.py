#!/usr/bin/env python3
"""Generate engines/paulstretch_tables.h (fixed-point tables for engines/paulstretch_dsp.c).

  ps_sin_q   sin(2 pi k / PS_NMAX), k = 0..PS_NMAX/4 (quarter wave, Q15): FFT twiddles and random phases
  ps_win     paulstretch window (1 - x^2)^1.25, first half of PS_NMAX points (symmetric), Q15;
             x = -1 + (2n + 1) / PS_NMAX (sample centres); smaller N read it at stride PS_NMAX / N
"""
import math, os
HERE = os.path.dirname(os.path.abspath(__file__))
NMAX = 16384

def emit(name, ctype, vals, per=16):
    rows = [', '.join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f'static const {ctype} {name}[{len(vals)}] = {{\n  ' + ',\n  '.join(rows) + '\n};\n'

q15 = lambda v: max(-32768, min(32767, int(round(v * 32767))))
out = ['/* generated by engines/gen_paulstretch_tables.py - do not edit */', '#include <stdint.h>',
       f'#define PS_NMAX {NMAX}']
out.append(emit('ps_sin_q', 'int16_t', [q15(math.sin(2 * math.pi * k / NMAX)) for k in range(NMAX // 4 + 1)]))
out.append(emit('ps_win', 'int16_t', [q15((1 - (-1 + (2 * n + 1) / NMAX) ** 2) ** 1.25) for n in range(NMAX // 2)]))
open(os.path.join(HERE, 'paulstretch_tables.h'), 'w').write('\n'.join(out))
print('ok', os.path.join(HERE, 'paulstretch_tables.h'))
