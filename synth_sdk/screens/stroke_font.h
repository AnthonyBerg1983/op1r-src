/* text at (x, y) top-left, scale s px per grid unit (Q10); returns the x after the text */
static int32_t sf_text(void *r, int32_t x, int32_t y, int32_t s, const char *t, int32_t w, const uint8_t *c)
{
    for (; *t; t++) {
        for (unsigned k = 0; k < sizeof sf_font / sizeof sf_font[0]; k++) if (sf_font[k].c == *t) {
            for (int j = 0; j < sf_font[k].n; j++) {
                const uint8_t *g = sf_font[k].seg[j];
                sf_line(r, x + g[0] * s, y + g[1] * s, x + g[2] * s, y + g[3] * s, w, c);
            }
            break;
        }
        x += (*t == '1' || *t == '.' ? 4 : 6) * s;
    }
    return x;
}
