#!/usr/bin/env python3
"""Generate gr_map.h (the Grids drum map) from Mutable Instruments' grids/resources.cc and pattern_generator.cc.

    python3 grids/gen_map.py PATH/TO/eurorack/grids      (pichenettes/eurorack, GPL-3.0, (c) 2011 Emilie Gillet)

The 25 nodes (3 parts x 32 steps of trigger levels) are placed on the 5 x 5 map in the order of pattern_generator.cc's
drum_map[5][5]."""
import os, re, sys

src = sys.argv[1]
res = open(os.path.join(src, 'resources.cc')).read()
pg = open(os.path.join(src, 'pattern_generator.cc')).read()
nodes = {}
for m in re.finditer(r'const prog_uint8_t node_(\d+)\[\] PROGMEM = \{(.*?)\};', res, re.S):
    v = [int(x) for x in re.findall(r'\d+', m.group(2))]
    assert len(v) == 96, (m.group(1), len(v))
    nodes[int(m.group(1))] = v
assert sorted(nodes) == list(range(25))
grid = re.search(r'drum_map\[5\]\[5\] = \{(.*?)\};', pg, re.S).group(1)
rows = [[int(n) for n in re.findall(r'node_(\d+)', r)] for r in re.findall(r'\{([^}]*)\}', grid)]
assert len(rows) == 5 and all(len(r) == 5 for r in rows)
out = ['/* generated by grids/gen_map.py from Mutable Instruments Grids (resources.cc, pattern_generator.cc).',
       ' * Copyright 2011 Emilie Gillet. GPL-3.0-or-later (pichenettes/eurorack, AVR code). Do not edit. */',
       '#ifndef GR_MAP_H', '#define GR_MAP_H', '#include <stdint.h>',
       '/* gr_map[i][j][part * 32 + step]: i = x >> 6, j = y >> 6 (as drum_map[i][j]); level 0..255 */',
       'static const uint8_t gr_map[5][5][96] = {']
for i, r in enumerate(rows):
    out.append('  {')
    for j, n in enumerate(r):
        v = nodes[n]
        out.append('    { /* node %d */' % n)
        for k in range(0, 96, 16):
            out.append('      ' + ', '.join('%3d' % x for x in v[k:k + 16]) + ',')
        out.append('    },')
    out.append('  },')
out += ['};', '#endif', '']
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'gr_map.h'), 'w').write('\n'.join(out))
print('-> gr_map.h')
