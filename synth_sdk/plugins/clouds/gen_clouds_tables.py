#!/usr/bin/env python3
"""Generate fx/clouds_tables.h (fixed-point tables for the Clouds port, fx/clouds_dsp.c).

Tables taken from the original (third_party/eurorack/clouds/resources.cc): lut_window, lut_xfade_in/out,
lut_grain_size. Derived: SoftLimit curve, 2^(x/12) for pitch, cosine for the reverb LFO.
"""
import math, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, '..', '..', 'third_party', 'eurorack', 'clouds', 'resources.cc')

def table(name):
    src = open(RES).read()
    m = re.search(r'const float %s\[\] = \{(.*?)\};' % name, src, re.S)
    return [float(v) for v in m.group(1).replace('\n', ' ').split(',') if v.strip()]

def emit(name, ctype, vals, per=12):
    rows = [', '.join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f'static const {ctype} {name}[{len(vals)}] = {{\n  ' + ',\n  '.join(rows) + '\n};\n'

q15 = lambda v: max(-32768, min(32767, int(round(v * 32767))))
out = ['/* generated by plugins/clouds/gen_clouds_tables.py from Mutable Instruments Clouds resources.cc - do not edit\n * (c) 2014 Emilie Gillet, MIT License */', '#include <stdint.h>']
out.append(emit('cl_lut_window', 'int16_t', [q15(v) for v in table('lut_window')]))          # 4097, Q15
out.append(emit('cl_lut_xfade_in', 'int16_t', [q15(v) for v in table('lut_xfade_in')]))      # 17, Q15
out.append(emit('cl_lut_xfade_out', 'int16_t', [q15(v) for v in table('lut_xfade_out')]))    # 17, Q15
out.append(emit('cl_lut_grain_size', 'int32_t', [int(round(v * 256)) for v in table('lut_grain_size')]))  # samples Q8 @ 32 kHz
# SoftLimit(x) = x (27 + x^2) / (27 + 9 x^2) for x in [-8, 8], 1/256 steps (4097 points), Q15 output
sl = []
for i in range(4097):
    x = (i - 2048) / 256.0
    sl.append(max(-2**31, min(2**31 - 1, int(round(x * (27 + x * x) / (27 + 9 * x * x) * 32768)))))
out.append(emit('cl_soft_limit', 'int32_t', sl))
# 2^(k/(12*16)), k = 0..192 : one octave in 1/16 semitone steps, Q30
out.append(emit('cl_pow2_semi16', 'uint32_t', [int(round(2 ** (k / 192.0) * 2**30)) for k in range(193)]))
# cosine, 1024 + 1 points, Q15
out.append(emit('cl_cos', 'int16_t', [q15(math.cos(2 * math.pi * k / 1024)) for k in range(1025)]))
open(os.path.join(HERE, 'clouds_tables.h'), 'w').write('\n'.join(out))
print('ok', os.path.join(HERE, 'clouds_tables.h'))
