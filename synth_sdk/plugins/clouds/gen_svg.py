#!/usr/bin/env python3
"""Generate display/cloudsfx.svg + fx/clouds_geom.h (screen of the clouds FX).

Minimal: the recording buffer as a horizontal line (write head at the left, older audio to the right, so the
blue POSITION knob moves the marker / grains to the right as it is turned up), grains drawn by code as
dots at their read position (size = envelope), a blue bracket for the position window, four dials in a
row. Code also marks page-2 dials (ring) and freeze (buffer line lit, head marker grey).
Never name it clouds.svg / any stock display file.
"""
import math, os
HERE = os.path.dirname(os.path.abspath(__file__))
GREY = '#6F7173'
BUF_X0, BUF_X1, BUF_Y = 20, 300, 58
DIAL_Y = 128
DIALS = [(70, '#4D9EFF'), (130, '#00ED95'), (190, '#FFFFFF'), (250, '#FF3A5D')]

def svg():
    o = ['<?xml version="1.0" encoding="utf-8"?>',
         '<svg version="1.1" id="Layer_1" xmlns="http://www.w3.org/2000/svg" x="0px" y="0px"',
         '\t width="320px" height="160px" viewBox="0 0 320 160">',
         '<!-- generated by display/gen_clouds_svg.py - clouds FX: buffer line, grains / rings / freeze by code -->',
         f'<line fill="none" stroke="{GREY}" stroke-width="1" x1="{BUF_X0}" y1="{BUF_Y}" x2="{BUF_X1}" y2="{BUF_Y}"/>',
         f'<line fill="none" stroke="{GREY}" stroke-width="1" x1="{BUF_X1}" y1="{BUF_Y - 4}" x2="{BUF_X1}" y2="{BUF_Y + 4}"/>']   # oldest end
    for x, c in DIALS:
        for a in (-135, 0, 135):
            t = math.radians(a); s, co = math.sin(t), math.cos(t)
            p = lambda r: (round(x + r * s, 1), round(DIAL_Y - r * co, 1))
            (x1, y1), (x2, y2) = p(11), p(13)
            o.append(f'<line fill="none" stroke="{GREY}" stroke-width="2" stroke-linecap="square" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"/>')
    for i, (x, c) in enumerate(DIALS):
        o.append(f'<circle id="base{i}" fill="{c}" cx="{x}" cy="{DIAL_Y}" r="2.8"/>')
    for i, (x, c) in enumerate(DIALS):
        o.append(f'<line id="bar{i}" fill="none" stroke="{c}" stroke-width="2" stroke-linecap="square" x1="{x}" y1="{DIAL_Y}" x2="{x}" y2="{DIAL_Y - 9}"/>')
    o.append('</svg>')
    return '\n'.join(o) + '\n'

def header():
    return '\n'.join(['/* generated by display/gen_clouds_svg.py - geometry of display/cloudsfx.svg */',
        f'#define CS_BUF_X0 {BUF_X0}', f'#define CS_BUF_X1 {BUF_X1}', f'#define CS_BUF_Y {BUF_Y}', f'#define CS_DIAL_Y {DIAL_Y}',
        'static const int16_t cs_dial_x[4] = { ' + ', '.join(str(x) for x, _ in DIALS) + ' };',
        'static const uint8_t cs_dial_col[4][4] = { ' + ', '.join(
            '{ %d, %d, %d, 255 }' % tuple(int(c[i:i + 2], 16) for i in (1, 3, 5)) for _, c in DIALS) + ' };']) + '\n'

if __name__ == '__main__':
    open(os.path.join(HERE, 'cloudsfx.svg'), 'w').write(svg())
    open(os.path.join(HERE, 'clouds_geom.h'), 'w').write(header())
    print('ok')
