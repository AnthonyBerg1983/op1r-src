#!/usr/bin/env python3
"""Generate display/tapeecho.svg + fx/tape_geom.h (shared geometry for the tape FX screen).

Vintage tape echo: a long tape loop runs over erase / record / play heads and the capstan along the top,
then winds through a serpentine of guide rollers (9 rollers in total). Each knob sits above the part it
controls, joined by a thin line:
    blue  (age)      -> erase head        green (feedback) -> record head
    white (time)     -> play head         red   (wow)      -> capstan / pinch roller
(left to right in OP-1 knob order)
Signal paths: input LED (in the knob row, above the record head) -> summing node -> record head, and
play head -> feedback amp (green knob) -> summing node on a lane above the heads. Heads, LED, lanes and the amp are drawn by code (fx/tape.c) so
their brightness can follow the knobs / levels. Code also turns the roller spokes and moves the tape gaps.
Never name it tape.svg: that is the stock tape screen.
"""
import math, os

HERE = os.path.dirname(os.path.abspath(__file__))
GREY, LIGHT, PURPLEGREY = '#6F7173', '#DFD9FF', '#AEB1DC'
TOP_Y, ZIG_TOP, ZIG_BOT, LEFT, RIGHT = 70, 96, 146, 14, 306
KNOB_Y = 20                                  # dial centres
FRAME_Y = 37                                 # top of the machine frame
LANE_Y = 46                                  # signal lane (input / feedback) above the heads
HEAD_HW = 6                                  # head half width
HEAD_TOP = TOP_Y - 13                        # heads span HEAD_TOP .. TOP_Y - 2
ERASE_X, REC_X, PLAY_X, CAPSTAN_X = 74, 126, 210, 262
LED_X, LED_Y = 126, KNOB_Y                   # input LED, in the knob row directly above the record head
SUM_X = 126                                  # summing node above the record head (= REC_X)
AMP_X = 168                                  # feedback amp (triangle pointing left), under the green knob
R = 5                                        # roller radius
# knob index -> (x, colour); order = OP-1 knob order blue, green, white, red
DIALS = [(ERASE_X, '#4D9EFF'), (AMP_X, '#00ED95'), (PLAY_X + HEAD_HW, '#FFFFFF'), (CAPSTAN_X, '#FF3A5D')]

# tape centre line (closed loop), travelling left -> right over the heads; 5 serpentine turns
N_ZIG = 5
step = (RIGHT - LEFT) / (N_ZIG + 1)
zig = [(round(RIGHT - step * (i + 1)), ZIG_TOP if i % 2 == 0 else ZIG_BOT) for i in range(N_ZIG)]
PATH = [(LEFT, TOP_Y), (RIGHT, TOP_Y), (RIGHT, ZIG_BOT)] + zig + [(LEFT, ZIG_BOT)]

def rollers():
    """roller centre at every corner, on the inside of the bend; spin sign from the bend direction"""
    out, n = [], len(PATH)
    for i, (px, py) in enumerate(PATH):
        ax, ay = PATH[i - 1]; bx, by = PATH[(i + 1) % n]
        d1 = (px - ax, py - ay); d2 = (bx - px, by - py)
        l1, l2 = math.hypot(*d1), math.hypot(*d2)
        u1 = (d1[0] / l1, d1[1] / l1); u2 = (d2[0] / l2, d2[1] / l2)
        cross = u1[0] * u2[1] - u1[1] * u2[0]
        ix, iy = u2[0] - u1[0], u2[1] - u1[1]; il = math.hypot(ix, iy)
        out.append((round(px + R * ix / il, 1), round(py + R * iy / il, 1), 1 if cross > 0 else -1))
    return out

ROLL = rollers()

def svg():
    o = ['<?xml version="1.0" encoding="utf-8"?>',
         '<svg version="1.1" id="Layer_1" xmlns="http://www.w3.org/2000/svg" x="0px" y="0px"',
         '\t width="320px" height="160px" viewBox="0 0 320 160">',
         '<!-- generated by display/gen_tape_svg.py - tape echo. Heads, LED, moving gaps and spoke rotation',
         '     (s0..sN, pinch) are drawn / animated by fx/tape.c. -->',
         f'<rect fill="none" stroke="{GREY}" stroke-width="1" x="4" y="{FRAME_Y}" width="312" height="{156 - FRAME_Y}"/>']
    pts = ' '.join(f'{x},{y}' for x, y in PATH + [PATH[0]])
    o.append(f'<polyline fill="none" stroke="{LIGHT}" stroke-width="1.5" stroke-linejoin="round" points="{pts}"/>')
    for cx, cy, _ in ROLL:
        o.append(f'<circle fill="#000000" stroke="{PURPLEGREY}" stroke-width="1" cx="{cx}" cy="{cy}" r="{R - 1}"/>')
    for i, (cx, cy, _) in enumerate(ROLL):
        o.append(f'<line id="s{i}" fill="none" stroke="{PURPLEGREY}" stroke-width="1" '
                 f'x1="{cx}" y1="{round(cy - R + 2, 1)}" x2="{cx}" y2="{round(cy + R - 2, 1)}"/>')
    # capstan (below the tape) + pinch roller (above)
    o.append(f'<circle fill="{PURPLEGREY}" cx="{CAPSTAN_X}" cy="{TOP_Y + 4}" r="3"/>')
    o.append(f'<circle fill="#000000" stroke="{PURPLEGREY}" stroke-width="1" cx="{CAPSTAN_X}" cy="{TOP_Y - 6}" r="5"/>')
    o.append(f'<line id="pinch" fill="none" stroke="{PURPLEGREY}" stroke-width="1" '
             f'x1="{CAPSTAN_X}" y1="{TOP_Y - 9}" x2="{CAPSTAN_X}" y2="{TOP_Y - 3}"/>')
    # connection lines knob -> element (green ends on the feedback amp, white on the play head's right corner)
    for x, _ in DIALS:
        y2 = {CAPSTAN_X: TOP_Y - 12, AMP_X: LANE_Y - 3.5}.get(x, HEAD_TOP - 1)   # green: onto the amp's edge
        o.append(f'<line fill="none" stroke="{GREY}" stroke-width="1" x1="{x}" y1="{KNOB_Y + 15}" x2="{x}" y2="{y2}"/>')
    # LED bezel (code fills it with the input level, r 4.5) and the summing node
    o.append(f'<circle fill="none" stroke="{GREY}" stroke-width="1" cx="{LED_X}" cy="{LED_Y}" r="6.5"/>')
    o.append(f'<circle fill="#000000" stroke="{LIGHT}" stroke-width="1" cx="{SUM_X}" cy="{LANE_Y}" r="3.5"/>')
    # dials (as granular / fmbell)
    for x, c in DIALS:
        y = KNOB_Y
        for a in (-135, 0, 135):
            t = math.radians(a); s, co = math.sin(t), math.cos(t)
            p = lambda r: (round(x + r * s, 1), round(y - r * co, 1))
            (x1, y1), (x2, y2) = p(11), p(13)
            o.append(f'<line fill="none" stroke="{GREY}" stroke-width="2" stroke-linecap="square" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"/>')
    for i, (x, c) in enumerate(DIALS):
        o.append(f'<circle id="base{i}" fill="{c}" cx="{x}" cy="{KNOB_Y}" r="2.8"/>')
    for i, (x, c) in enumerate(DIALS):
        o.append(f'<line id="bar{i}" fill="none" stroke="{c}" stroke-width="2" stroke-linecap="square" x1="{x}" y1="{KNOB_Y}" x2="{x}" y2="{KNOB_Y - 9}"/>')
    o.append('</svg>')
    return '\n'.join(o) + '\n'

def header():
    n = len(PATH)
    seg = [math.hypot(PATH[(i + 1) % n][0] - PATH[i][0], PATH[(i + 1) % n][1] - PATH[i][1]) for i in range(n)]
    h = ['/* generated by display/gen_tape_svg.py - geometry of display/tapeecho.svg */',
         f'#define TP_N {n}', f'#define TP_ROLLERS {len(ROLL)}', f'#define TP_R {R}',
         f'#define TP_TOP_Y {TOP_Y}', f'#define TP_HEAD_TOP {HEAD_TOP}', f'#define TP_KNOB_Y {KNOB_Y}',
         f'#define TP_ERASE_X {ERASE_X}', f'#define TP_REC_X {REC_X}', f'#define TP_PLAY_X {PLAY_X}',
         f'#define TP_CAPSTAN_X {CAPSTAN_X}', f'#define TP_LED_X {LED_X}', f'#define TP_LED_Y {LED_Y}',
         f'#define TP_LANE_Y {LANE_Y}', f'#define TP_SUM_X {SUM_X}', f'#define TP_AMP_X {AMP_X}',
         f'#define TP_HEAD_HW {HEAD_HW}',
         f'#define TP_LOOP_LEN {int(round(sum(seg)))}',
         'static const int16_t tp_pt[TP_N][2] = { ' + ', '.join(f'{{{x}, {y}}}' for x, y in PATH) + ' };',
         'static const int16_t tp_len[TP_N] = { ' + ', '.join(str(int(round(s))) for s in seg) + ' };   /* segment i -> i+1 */',
         '/* roller centres in Q10 + spin direction */',
         'static const int32_t tp_roll[TP_ROLLERS][3] = { ' +
         ', '.join(f'{{{int(round(x * 1024))}, {int(round(y * 1024))}, {d}}}' for x, y, d in ROLL) + ' };',
         'static const int16_t tp_dial[4][2] = { ' + ', '.join(f'{{{x}, {KNOB_Y}}}' for x, _ in DIALS) + ' };']
    return '\n'.join(h) + '\n'

if __name__ == '__main__':
    open(os.path.join(HERE, 'tapeecho.svg'), 'w').write(svg())
    open(os.path.join(HERE, 'tape_geom.h'), 'w').write(header())
    print(f'{len(PATH)} path points, {len(ROLL)} rollers')
