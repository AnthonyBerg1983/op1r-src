#!/usr/bin/env python3
"""Generate display/supersaw.svg + engines/supersaw_geom.h (shared geometry for the supersaw screen).

Minimal line-art chainsaw (side view): rear handle, engine body, top handle, guide bar with a nose
sprocket. Four iter-style dials in a row at the bottom (blue detune, green morph, white sub, red drive).
Code (engines/supersaw.c) draws the chain: top run = the oscillator waveform as teeth (saw -> square with
morph) plus a dim blue detuned copy drifting against it, bottom run = sub-octave teeth (height = sub).
Parts light up with their knob (drawn by code from the geometry exported here): fuel cap blue (detune),
top handle green (morph), smoke puffs from the exhaust white (sub), trigger red (drive); the whole saw
(group "saw") shakes with drive while notes play.
"""
import math, os

def bezier(p0, p1, p2, p3, n=6):
    return [tuple(round((1-t)**3*a + 3*(1-t)**2*t*b + 3*(1-t)*t*t*c + t**3*d, 1)
                  for a, b, c, d in zip(p0, p1, p2, p3)) for t in (i / n for i in range(1, n + 1))]

# wrap-around top handle (code-drawn, green): rear of body up, forward, down to the front
HANDLE = [(48, 40), (48, 26)] + bezier((48, 26), (48, 18), (54, 14), (62, 14)) + [(86, 14)] + \
         bezier((86, 14), (94, 14), (98, 20), (98, 28)) + [(98, 40)]
CAP = (52, 84, 4)                                            # fuel cap (code-drawn, blue)
EXHAUST = (35, 44)                                           # smoke puffs rise from here (white)

HERE = os.path.dirname(os.path.abspath(__file__))
GREY, LIGHT, PURPLEGREY = '#6F7173', '#DFD9FF', '#AEB1DC'
BAR_X0, BAR_X1, BAR_TOP, BAR_BOT = 118, 300, 50, 74          # guide bar (nose = half circle at the right)
NOSE_R = (BAR_BOT - BAR_TOP) / 2
NOSE_X = BAR_X1 - NOSE_R
CHAIN_X0, CHAIN_X1 = BAR_X0 + 4, NOSE_X                      # straight chain runs
SPROCKET = (NOSE_X, (BAR_TOP + BAR_BOT) / 2, 4)
TRIGGER = ((19, 84), (33, 84))                               # code-drawn trigger in the rear grip (red, drive)
DIAL_Y = 136
DIALS = [(70, '#4D9EFF'), (130, '#00ED95'), (190, '#FFFFFF'), (250, '#FF3A5D')]

def k(v):                       # 4/3*tan(theta/4) for a quarter circle
    return v * 0.5523

def svg():
    o = ['<?xml version="1.0" encoding="utf-8"?>',
         '<svg version="1.1" id="Layer_1" xmlns="http://www.w3.org/2000/svg" x="0px" y="0px"',
         '\t width="320px" height="160px" viewBox="0 0 320 160">',
         '<!-- generated by display/gen_supersaw_svg.py - minimal chainsaw; chain, trigger glow and shake by code -->',
         '<g id="saw">']
    st = f'fill="none" stroke="{LIGHT}" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"'
    # engine body: slanted front, rounded rear
    o.append(f'<path {st} d="M52,40L98,40L116,50L116,92L52,92C46,92 42,88 42,82L42,50C42,44 46,40 52,40Z"/>')
    # rear handle: D loop behind the body
    o.append(f'<path {st} d="M42,60L20,60C14,60 12,64 12,70L12,84C12,90 16,92 22,92L42,92"/>')
    # top handle + fuel cap: drawn by code (glow with their knobs)
    # front hand guard
    o.append(f'<line fill="none" stroke="{PURPLEGREY}" stroke-width="1.5" stroke-linecap="round" x1="106" y1="20" x2="114" y2="44"/>')
    # cooling slots + fuel cap
    for y in (58, 66, 74):
        o.append(f'<line fill="none" stroke="{GREY}" stroke-width="1.5" stroke-linecap="round" x1="62" y1="{y}" x2="100" y2="{y}"/>')
    o.append(f'<circle fill="none" stroke="{GREY}" stroke-width="1" cx="{EXHAUST[0] + 2}" cy="{EXHAUST[1]}" r="2"/>')   # exhaust port
    # guide bar with round nose
    r = NOSE_R
    o.append(f'<path {st} d="M{BAR_X0},{BAR_TOP}L{NOSE_X},{BAR_TOP}'
             f'C{NOSE_X + k(r):.1f},{BAR_TOP} {BAR_X1},{BAR_TOP + r - k(r):.1f} {BAR_X1},{BAR_TOP + r}'
             f'C{BAR_X1},{BAR_TOP + r + k(r):.1f} {NOSE_X + k(r):.1f},{BAR_BOT} {NOSE_X},{BAR_BOT}'
             f'L{BAR_X0},{BAR_BOT}"/>')
    o.append(f'<line fill="none" stroke="{GREY}" stroke-width="1" x1="{BAR_X0 + 10}" y1="{(BAR_TOP + BAR_BOT) / 2}" '
             f'x2="{NOSE_X - 14}" y2="{(BAR_TOP + BAR_BOT) / 2}"/>')
    sx, sy, sr = SPROCKET
    o.append(f'<circle fill="none" stroke="{PURPLEGREY}" stroke-width="1" cx="{sx}" cy="{sy}" r="{sr}"/>')
    o.append('</g>')
    o.append(f'<line id="sprk" fill="none" stroke="{PURPLEGREY}" stroke-width="1" x1="{sx}" y1="{sy - sr + 1}" x2="{sx}" y2="{sy + sr - 1}"/>')
    # dials
    for x, c in DIALS:
        for a in (-135, 0, 135):
            t = math.radians(a); s, co = math.sin(t), math.cos(t)
            p = lambda rr: (round(x + rr * s, 1), round(DIAL_Y - rr * co, 1))
            (x1, y1), (x2, y2) = p(11), p(13)
            o.append(f'<line fill="none" stroke="{GREY}" stroke-width="2" stroke-linecap="square" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"/>')
    for i, (x, c) in enumerate(DIALS):
        o.append(f'<circle id="base{i}" fill="{c}" cx="{x}" cy="{DIAL_Y}" r="2.8"/>')
    for i, (x, c) in enumerate(DIALS):
        o.append(f'<line id="bar{i}" fill="none" stroke="{c}" stroke-width="2" stroke-linecap="square" x1="{x}" y1="{DIAL_Y}" x2="{x}" y2="{DIAL_Y - 9}"/>')
    o.append('</svg>')
    return '\n'.join(o) + '\n'

def header():
    sx, sy, _ = SPROCKET
    (tx0, ty0), (tx1, ty1) = TRIGGER
    h = ['/* generated by display/gen_supersaw_svg.py - geometry of display/supersaw.svg */',
         f'#define SS_CHAIN_X0 {CHAIN_X0}', f'#define SS_CHAIN_X1 {int(CHAIN_X1)}',
         f'#define SS_BAR_TOP {BAR_TOP}', f'#define SS_BAR_BOT {BAR_BOT}',
         f'#define SS_SPRK_X {sx:g}', f'#define SS_SPRK_Y {sy:g}',
         f'#define SS_TRIG_X0 {tx0}', f'#define SS_TRIG_Y0 {ty0}', f'#define SS_TRIG_X1 {tx1}', f'#define SS_TRIG_Y1 {ty1}',
         f'#define SS_DIAL_Y {DIAL_Y}',
         f'#define SS_CAP_X {CAP[0]}', f'#define SS_CAP_Y {CAP[1]}', f'#define SS_CAP_R {CAP[2]}',
         f'#define SS_EXH_X {EXHAUST[0]}', f'#define SS_EXH_Y {EXHAUST[1]}',
         f'#define SS_HANDLE_N {len(HANDLE)}',
         'static const int32_t ss_handle[SS_HANDLE_N][2] = { ' +
         ', '.join(f'{{{int(round(x * 1024))}, {int(round(y * 1024))}}}' for x, y in HANDLE) + ' };   /* Q10 */',
         'static const int16_t ss_dial_x[4] = { ' + ', '.join(str(x) for x, _ in DIALS) + ' };']
    return '\n'.join(h) + '\n'

if __name__ == '__main__':
    open(os.path.join(HERE, 'supersaw.svg'), 'w').write(svg())
    open(os.path.join(HERE, 'supersaw_geom.h'), 'w').write(header())
    print('ok')
